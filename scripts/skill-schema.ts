// Regenerates skills/brainrotnt-problems/references/schema.md from the bridge's own schema code, so the
// snapshot an agent reads offline matches what get_schema serves. --check exits 1 when it is stale.
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

// get_schema's module graph opens the database at import time; keep it in memory.
process.env.DB_PATH = ":memory:";
const { getSchema } = await import("../apps/bridge/src/features/get-schema/query");

const root = resolve(import.meta.dir, "..");
const out = join(root, "skills/brainrotnt-problems/references/schema.md");
const schema = getSchema();
const block = (value: unknown) => "```json\n" + JSON.stringify(value, null, 2) + "\n```";

const text = `# Schema snapshot

Generated by \`bun run skills:schema\` from the bridge's schema code. Do not edit by hand. The live \`get_schema\` MCP tool always wins over this file.

## Supported values

${block(schema.supported)}

## Limits

${block(schema.limits)}

## Notes

${schema.notes.map((note) => `- ${note}`).join("\n")}

## problemSpec (math, stats, physics, code)

${block(schema.problemSpec)}

## triviaSpec

${block(schema.triviaSpec)}

## templateSpec

${block(schema.templateSpec)}
`;

if (process.argv.includes("--check")) {
  const current = (() => {
    try {
      return readFileSync(out, "utf8");
    } catch {
      return "";
    }
  })();
  if (current !== text) {
    console.error("skills/brainrotnt-problems/references/schema.md is stale: run bun run skills:schema");
    process.exit(1);
  }
  console.log("schema snapshot is current");
} else {
  writeFileSync(out, text);
  console.log(`wrote ${out}`);
}
