// Builds the installable `brainrotnt` binary: the bridge with the web app, the database migrations and the
// authoring skill embedded, so it runs from one file and one port.
//
//   bun run build:release                                   this machine's platform, version "0.0.0-dev"
//   bun run build:release -- --target darwin-arm64 --version v0.3.0 [--skip-web]
//
// Output: dist/release/brainrotnt-<version>-<platform>.tar.gz holding a single `brainrotnt` file, the name
// install.sh downloads. Platforms: darwin-arm64, darwin-x64, linux-x64, linux-arm64.
import { $ } from "bun";
import { existsSync, mkdirSync, rmSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = join(import.meta.dir, "..");
const args = process.argv.slice(2);
const flag = (name: string) => {
  const i = args.indexOf(name);
  return i >= 0 ? args[i + 1] : undefined;
};

const PLATFORMS = ["darwin-arm64", "darwin-x64", "linux-x64", "linux-arm64"] as const;
const host = `${process.platform}-${process.arch === "x64" ? "x64" : "arm64"}`;
const platform = flag("--target") ?? host;
if (!(PLATFORMS as readonly string[]).includes(platform)) throw new Error(`unknown --target ${platform}; one of ${PLATFORMS.join(", ")}`);
const version = flag("--version") ?? "0.0.0-dev";
const outDir = join(root, "dist/release");

if (!args.includes("--skip-web")) {
  console.log("building the web app…");
  await $`bun run --filter web build`.cwd(root).quiet();
}
const webDist = join(root, "apps/web/dist");
if (!existsSync(join(webDist, "index.html"))) throw new Error("apps/web/dist/index.html is missing; build the web app first");

// The generated entry imports every file it embeds. `type: "file"` stores a file as-is in the binary
// (Bun.file can read it); `type: "text"` inlines it as a string.
const genDir = join(root, "apps/bridge/.release");
rmSync(genDir, { recursive: true, force: true });
mkdirSync(genDir, { recursive: true });
const spec = (file: string) => JSON.stringify(relative(genDir, file).split("\\").join("/"));
const imports: string[] = [];
let n = 0;
const embed = (file: string, type: "file" | "text") => {
  const name = `e${n++}`;
  imports.push(`import ${name} from ${spec(file)} with { type: ${JSON.stringify(type)} };`);
  return name;
};

const web: string[] = [];
for await (const file of new Bun.Glob("**/*").scan({ cwd: webDist, onlyFiles: true })) {
  web.push(`  [${JSON.stringify(`/${file.split("\\").join("/")}`)}, ${embed(join(webDist, file), "file")}],`);
}

const drizzle = join(root, "apps/bridge/drizzle");
const journal = JSON.parse(await Bun.file(join(drizzle, "meta/_journal.json")).text()) as { entries: { tag: string }[] };
const journalText = embed(join(drizzle, "meta/_journal.json"), "text");
const sql = journal.entries.map(({ tag }) => `    ${JSON.stringify(tag)}: ${embed(join(drizzle, `${tag}.sql`), "text")},`);

const skillDir = join(root, "skills/brainrotnt-problems");
const skill: string[] = [];
for await (const file of new Bun.Glob("**/*").scan({ cwd: skillDir, onlyFiles: true })) {
  skill.push(`  ${JSON.stringify(file.split("\\").join("/"))}: ${embed(join(skillDir, file), "text")},`);
}

const entry = join(genDir, "entry.ts");
writeFileSync(
  entry,
  `// Generated by scripts/build-release.ts; do not edit.
${imports.join("\n")}
import { run } from ${spec(join(root, "apps/bridge/src/cli/main.ts"))};

await run({
  version: ${JSON.stringify(version)},
  webAssets: new Map<string, string>([
${web.join("\n")}
  ]),
  migrations: {
    embedded: {
      journal: ${journalText},
      sql: {
${sql.join("\n")}
      },
    },
  },
  skill: {
${skill.join("\n")}
  },
});
`,
);

const stage = join(outDir, `brainrotnt-${version}-${platform}`);
rmSync(stage, { recursive: true, force: true });
mkdirSync(stage, { recursive: true });
const binary = join(stage, "brainrotnt");
console.log(`compiling ${version} for ${platform} (${web.length} web files, ${sql.length} migrations, ${skill.length} skill files)…`);
await $`bun build --compile --minify --sourcemap=none --target=bun-${platform} ${entry} --outfile ${binary}`.cwd(join(root, "apps/bridge")).quiet();

// Apple Silicon refuses to run unsigned binaries; an ad-hoc signature is enough for a downloaded CLI.
if (platform.startsWith("darwin") && process.platform === "darwin") await $`codesign --force --sign - ${binary}`.quiet();

const archive = join(outDir, `brainrotnt-${version}-${platform}.tar.gz`);
await $`tar -czf ${archive} -C ${stage} brainrotnt`;
rmSync(genDir, { recursive: true, force: true });
const size = (Bun.file(archive).size / 1024 / 1024).toFixed(1);
console.log(`built ${relative(root, archive)} (${size} MB)`);
